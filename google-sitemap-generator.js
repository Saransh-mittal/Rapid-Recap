const fs = require('fs').promises
const path = require('path')
const Article = require('./model/articleSchema')
const xml = require('xmlbuilder')
const { toISOString } = require('./utils/miscellaneous.utils')
const slugify = require('slugify')

const BASE_URL = 'https://www.rapidrecap.co.in'
const MAX_NEWS_ARTICLES = 1000 // Google News allows up to 1000 articles

async function generateGoogleNewsSitemap() {
  console.log('Starting Google News sitemap generation...')

  try {
    const now = new Date() // Current time
    const newsThreshold = new Date(
      now.getTime() - 48 * 60 * 60 * 1000,
    ).toISOString() // 48 hours ago in ISO string

    // Fetch the most recent articles from the past 48 hours
    const newsArticles = await Article.find({
      dateTime: { $gte: newsThreshold }, // Compare dateTime in ISO format
    })
      .sort({ dateTime: -1 })
      .limit(MAX_NEWS_ARTICLES)
      .select('_id dateTime title author')

    // If no articles are found, exit early
    if (!newsArticles.length) {
      console.log('No recent news articles found for Google News sitemap.')
      return
    }

    // Generate XML for the Google News sitemap
    const root = xml
      .create('urlset', { version: '1.0', encoding: 'UTF-8' })
      .att('xmlns', 'http://www.sitemaps.org/schemas/sitemap/0.9')
      .att('xmlns:news', 'http://www.google.com/schemas/sitemap-news/0.9')

    newsArticles.forEach(article => {
      const url = root.ele('url')
      url.ele(
        'loc',
        `${BASE_URL}/article/${article._id}/${slugify(article.title)}`,
      )
      url
        .ele('news:news')
        .ele('news:publication')
        .ele('news:name', 'Rapid Recap')
        .up()
        .ele('news:language', 'en')
        .up()
        .up() // Set to 'hi' for Hindi articles if needed
        .ele('news:publication_date', toISOString(article.dateTime))
        .up()
        .ele('news:title', article.title)
        .up()
        .ele(
          'news:author',
          article.author || 'AI Generated by Rapid Recap Team',
        )
        .up()
    })

    const sitemap = root.end({ pretty: true })

    // Write Google News sitemap to file
    //
    const outputPath = path.join(
      __dirname,
      './client/dist',
      'google-news-sitemap.xml',
    )
    await fs.writeFile(outputPath, sitemap)

    console.log(`Google News Sitemap generated successfully at ${outputPath}`)
  } catch (error) {
    console.error('Error generating Google News sitemap:', error)
  }
}

module.exports = generateGoogleNewsSitemap
